/**
 * Mock destination guides until the guide service exists. Each place keeps its
 * Google place id so the card can load its current photo and rating live;
 * ratings and photos are deliberately not stored here.
 */
function googlePlace(
  providerPlaceId: string,
  name: string,
  address: string,
  lat: number,
  lng: number,
  primaryType: string,
  category: string,
  blurb: string,
  tags: readonly string[],
): GuidePlace {
  return {
    id: `GOOGLE:${providerPlaceId}`,
    provider: "GOOGLE",
    providerPlaceId,
    name,
    address,
    lat,
    lng,
    primaryType,
    category,
    description: category,
    blurb,
    tags,
  };
}

